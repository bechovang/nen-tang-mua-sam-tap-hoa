CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    barcode VARCHAR(32) NOT NULL,
    name VARCHAR(120) NOT NULL,
    price BIGINT NOT NULL,
    unit VARCHAR(20) NOT NULL,
    stock INT NOT NULL DEFAULT 0,
    image_key VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT true,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT products_store_barcode_unique UNIQUE (store_id, barcode)
);

CREATE INDEX products_store_active_idx ON products(store_id, active, deleted_at);
CREATE INDEX products_name_idx ON products(lower(name));

CREATE TABLE barcode_cache (
    barcode VARCHAR(32) PRIMARY KEY,
    name VARCHAR(255),
    image_url VARCHAR(500),
    source VARCHAR(32) NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE stock_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    delta INT NOT NULL,
    reason VARCHAR(32) NOT NULL,
    order_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX stock_events_product_idx ON stock_events(product_id, created_at);
