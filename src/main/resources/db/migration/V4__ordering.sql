CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(24) NOT NULL UNIQUE,
    store_id BIGINT NOT NULL REFERENCES stores(id),
    customer_id BIGINT REFERENCES users(id),
    type VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL,
    fulfillment VARCHAR(16) NOT NULL,
    delivery_address VARCHAR(255),
    phone VARCHAR(20),
    note VARCHAR(500),
    subtotal BIGINT NOT NULL DEFAULT 0,
    delivery_fee BIGINT NOT NULL DEFAULT 0,
    total BIGINT NOT NULL DEFAULT 0,
    pickup_start TIMESTAMPTZ,
    pickup_end TIMESTAMPTZ,
    hold_until TIMESTAMPTZ,
    idempotency_key VARCHAR(64),
    paid BOOLEAN NOT NULL DEFAULT false,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT orders_customer_idempotency_unique UNIQUE (customer_id, idempotency_key)
);

CREATE INDEX orders_customer_idx ON orders(customer_id, created_at DESC);
CREATE INDEX orders_store_status_idx ON orders(store_id, status, created_at DESC);
CREATE INDEX orders_pickup_idx ON orders(status, hold_until);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id),
    name_snapshot VARCHAR(120) NOT NULL,
    unit_price_snapshot BIGINT NOT NULL,
    unit_snapshot VARCHAR(20) NOT NULL,
    quantity INT NOT NULL,
    picked_quantity INT NOT NULL DEFAULT 0,
    stock_reserved BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL,
    actor_id BIGINT,
    note VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pos_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX one_open_pos_session ON pos_sessions(store_id) WHERE status = 'OPEN';

CREATE TABLE pos_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES pos_sessions(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id),
    name_snapshot VARCHAR(120) NOT NULL,
    unit_price_snapshot BIGINT NOT NULL,
    unit_snapshot VARCHAR(20) NOT NULL,
    quantity INT NOT NULL
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(32) NOT NULL,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(500),
    read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX notifications_user_idx ON notifications(user_id, read, created_at DESC);
